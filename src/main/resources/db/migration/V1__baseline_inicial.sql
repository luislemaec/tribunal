-- ============================================================================
-- TEC - Baseline inicial Flyway
-- ----------------------------------------------------------------------------
-- Uso previsto:
--   - Crear una base nueva desde cero.
--   - NO ejecutar sobre una base productiva existente.
--
-- Para una base existente usar:
--   baselineOnMigrate=true
--   baselineVersion=1
--
-- Los cambios posteriores deben iniciar en V2__descripcion.sql.
-- ============================================================================

DO $$
BEGIN
  IF EXISTS (
      SELECT 1
        FROM information_schema.tables
       WHERE table_schema IN ('public', 'tec')
         AND table_name IN (
             'tb_usuario', 'tb_rol', 'tb_persona', 'tb_iglesia',
             'padron', 'mesas', 'proceso_electoral', 'escrutinio'
         )
  ) THEN
    RAISE EXCEPTION 'V1__baseline_inicial.sql solo debe ejecutarse sobre una base nueva. Use baselineOnMigrate=true para bases existentes.';
  END IF;
END $$;

