CREATE OR REPLACE VIEW tec.vw_lugar_votacion AS
SELECT p.padron_id,
       i.igl_nombre AS iglesia,
       i.igl_comunidad_barrio AS comunicad,
       pe.pers_documento AS cedula,
       CONCAT_WS(' ', pe.pers_nombre, pe.pers_apellido) AS nombre,
       m.mesa_nombre AS mesa,
       r.rec_nombre AS recinto,
       parroquia.gelo_name AS parroquia,
       canton.gelo_name AS canton
  FROM tec.padron p
  JOIN public.tb_iglesia_persona ip ON ip.igpe_id = p.igpe_id
  JOIN public.tb_iglesia i ON i.igl_id = ip.igl_id
  JOIN public.tb_persona pe ON pe.pers_id = ip.pers_id
  JOIN tec.mesas m ON m.mesa_id = p.mesa_id
  JOIN tec.recintos r ON r.rec_id = m.rec_id
  LEFT JOIN public.tb_geograp parroquia ON parroquia.gelo_id = r.gelo_id
  LEFT JOIN public.tb_geograp canton ON canton.gelo_id = parroquia.gelo_parent_id
 WHERE COALESCE(p.estado, TRUE) = TRUE;

CREATE OR REPLACE VIEW tec.vw_total_escrutinios AS
SELECT e.escr_id,
       cv.nombre,
       e.total_votos AS t_votos,
       cv.cat_orden,
       r.rec_id,
       m.mesa_id,
       COALESCE(m.gelo_id, r.gelo_id) AS gelo_id,
       COALESCE(e.estado, TRUE) AS estado
  FROM tec.escrutinio e
  JOIN tec.categoria_voto cv ON cv.cat_voto_id = e.cat_voto_id
  JOIN tec.mesas m ON m.mesa_id = e.mesa_id
  LEFT JOIN tec.recintos r ON r.rec_id = m.rec_id;
