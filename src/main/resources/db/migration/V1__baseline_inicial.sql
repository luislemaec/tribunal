-- Tablas de auditoria Hibernate Envers
-- ----------------------------------------------------------------------------
-- Se crean a partir de la estructura base para evitar divergencia de tipos.
-- Envers usa por defecto sufijo _AUD; PostgreSQL normaliza a minusculas.
-- ============================================================================

CREATE TABLE public.tb_geograp_aud AS SELECT t.*, 0::INTEGER AS rev, 0::SMALLINT AS revtype FROM public.tb_geograp t WITH NO DATA;
ALTER TABLE public.tb_geograp_aud ADD PRIMARY KEY (gelo_id, rev);
ALTER TABLE public.tb_geograp_aud ADD CONSTRAINT fk_tb_geograp_aud_rev FOREIGN KEY (rev) REFERENCES tec.tec_auditoria(aud_id);

CREATE TABLE public.tb_persona_aud AS SELECT t.*, 0::INTEGER AS rev, 0::SMALLINT AS revtype FROM public.tb_persona t WITH NO DATA;
ALTER TABLE public.tb_persona_aud ADD PRIMARY KEY (pers_id, rev);
ALTER TABLE public.tb_persona_aud ADD CONSTRAINT fk_tb_persona_aud_rev FOREIGN KEY (rev) REFERENCES tec.tec_auditoria(aud_id);

CREATE TABLE public.tb_iglesia_aud AS SELECT t.*, 0::INTEGER AS rev, 0::SMALLINT AS revtype FROM public.tb_iglesia t WITH NO DATA;
