-- Notificaciones push de la App móvil CONPOCIIECH (docs/api-movil.md, «Notificaciones»).
-- No cambia migraciones anteriores, usuarios, roles ni la configuración de Elytron.
-- Desactivadas por defecto: TEC solo encola y envía con -Dtec.push.enabled=true y una
-- credencial de Firebase configurada fuera del repositorio.

-- Dispositivos de la App con su token de Firebase Cloud Messaging. Un token pertenece a un
-- solo usuario: si otro usuario inicia sesión en el mismo teléfono, el registro se reasigna.
CREATE TABLE tec.dispositivo_movil (
    disp_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usu_id INTEGER NOT NULL,
    token VARCHAR(512) NOT NULL,
    plataforma VARCHAR(10) NOT NULL,
    registrado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    actualizado_en TIMESTAMP WITH TIME ZONE NOT NULL,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT fk_dispositivo_movil_usuario FOREIGN KEY (usu_id) REFERENCES public.tb_usuario(usu_id),
    CONSTRAINT uk_dispositivo_movil_token UNIQUE (token),
    CONSTRAINT ck_dispositivo_movil_plataforma CHECK (plataforma IN ('android', 'ios'))
);
CREATE INDEX idx_dispositivo_movil_usuario ON tec.dispositivo_movil (usu_id) WHERE activo;

-- Bandeja de salida: el evento electoral encola en su misma transacción (si se revierte, no
-- hay aviso) y un proceso programado envía. El contenido es mínimo y sin datos personales.
CREATE TABLE tec.notificacion_movil (
    notif_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- USUARIO: destino = usu_id; ROL: destino = nombre del rol (SITEC-...).
    destino_tipo VARCHAR(10) NOT NULL,
    destino VARCHAR(80) NOT NULL,
    titulo VARCHAR(80) NOT NULL,
    cuerpo VARCHAR(200) NOT NULL,
    -- Pantalla de la App que se abre al tocar el aviso (ruta interna, p. ej. /tribunal/mesa).
    ruta VARCHAR(80),
    creada_en TIMESTAMP WITH TIME ZONE NOT NULL,
    enviada_en TIMESTAMP WITH TIME ZONE,
    intentos INTEGER NOT NULL DEFAULT 0,
    ultimo_error VARCHAR(200),
    CONSTRAINT ck_notificacion_movil_tipo CHECK (destino_tipo IN ('USUARIO', 'ROL'))
);
CREATE INDEX idx_notificacion_movil_pendiente ON tec.notificacion_movil (creada_en)
    WHERE enviada_en IS NULL;

-- Eventos del cronograma ya notificados (inicio de fase, inicio/fin del sufragio), para no
-- repetir el aviso en cada ejecución del proceso programado ni tras un reinicio.
CREATE TABLE tec.notificacion_evento (
    clave VARCHAR(120) PRIMARY KEY,
    registrado_en TIMESTAMP WITH TIME ZONE NOT NULL
);
